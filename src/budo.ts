// Order matters: 銃剣道/短剣道 contain 剣道.
const SPORTS: [RegExp, string][] = [
  [/銃剣道|短剣道/, "Jukendo"],
  [/剣道/, "Kendo"],
  [/柔道/, "Judo"],
  [/空手/, "Karate"],
  [/合気道/, "Aikido"],
  [/弓道/, "Kyudo"],
  [/少林寺/, "Shorinji Kempo"],
  [/なぎなた/, "Naginata"],
  [/古武道/, "Kobudo"],
  [/書/, "Calligraphy"],
  [/鏡開き/, "New Year ceremony"],
  [/武道/, "Martial arts"],
];

export function sportOf(name: string): string | undefined {
  return SPORTS.find(([re]) => re.test(name))?.[1];
}

const SOURCE = "https://www.nipponbudokan.or.jp/shinkoujigyou/gyouji_08";

// Last day covered by FY2026 above; /health flags the list as expired after this.
export const BUDO_VALID_UNTIL = "2027-03-31";

export function budoEvents(): BudokanEvent[] {
  return FY2026.flatMap(([dates, name, organizer]) =>
    dates.map((date) => ({
      date,
      kind: "budo" as const,
      headline: name,
      sport: sportOf(name),
      organizer,
      url: SOURCE,
      sources: ["nipponbudokan.or.jp"],
    })),
  );
}
